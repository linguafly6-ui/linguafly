export function getLegacyAdvancedUnit(level: string, unitNumber: number): LegacyAdvancedUnit | null {
  return units[level.toLowerCase()]?.[unitNumber] ?? null;
}
export function getLegacyAdvancedItem(lessonId: string, exerciseId: string): LegacyAdvancedItem | null {
  const match = /^(b1|b2|c1|c2)-(\\d{2})$/.exec(lessonId);
  if (!match) return null;
  const unit = getLegacyAdvancedUnit(match[1], Number(match[2]));
  return unit?.blocks.flatMap((block) => block.content).find((item) => item.interaction_id === exerciseId) ?? null;
}
export function getLegacyAdvancedSection(item: LegacyAdvancedItem, blockTitle = ""): string {
  const tag = (item.mastery_tag ?? "").toLowerCase();
  const concepts = (item.concept_tags ?? []).join(" ").toLowerCase();
  const text = `${tag} ${concepts} ${blockTitle.toLowerCase()} ${item.type.toLowerCase()}`;
  if (/listening|audio|listen/.test(text)) return "listening";
  if (/reading|comprehension|read/.test(text)) return "reading";
  if (/vocab|idiom|word-formation|word formation|collocation/.test(text)) return "vocabulary";
  if (/production|speaking|writing|communication/.test(text)) return "production";
  return "grammar";
}
